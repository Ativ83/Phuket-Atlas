#!/usr/bin/env python3
"""Regenerate ONLY Patong's Russian narration using Google Translate TTS.

This free backup avoids Edge TTS NoAudioReceived errors.
The public text and all other district MP3 files are unchanged.
"""
import json
import os
import tempfile
from pathlib import Path
from gtts import gTTS

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "district-narrations-ru.json"
OUTPUT = ROOT / "assets" / "district-audio" / "patong.mp3"

def main():
    narration = json.loads(SOURCE.read_text(encoding="utf-8"))["patong"]
    # No combining acute accent marks: they may make a TTS engine spell the name.
    narration = narration.replace("\u0301", "")
    assert "Патонг" in narration
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix="patong-", suffix=".mp3", dir=str(OUTPUT.parent))
    os.close(fd)
    try:
        gTTS(text=narration, lang="ru", slow=False).save(temp_name)
        size = Path(temp_name).stat().st_size
        if size < 10000:
            raise RuntimeError(f"Patong audio unexpectedly small: {size} bytes")
        Path(temp_name).replace(OUTPUT)
        print(f"Patong MP3 generated by backup gTTS: {size} bytes", flush=True)
    finally:
        Path(temp_name).unlink(missing_ok=True)

if __name__ == "__main__":
    main()
